"""Week 4 arith reopening pilot read-out.

Pre-registered gates (notes/week4-arith-pilot-design.md), fixed BEFORE any
arm number was seen:
  Anchors @ step 5000, seed 1:
    (a) delay-0 baseline    exact-match 0.798  val_ppl 48.19
    (b) d50 null            exact-match 0.506  val_ppl 50.83
  Recovery% = (arm - 0.506) / (0.798 - 0.506)   [gap = 0.292]
  Skill gate PRIMARY  : arm exact-match >= 0.718 (= 0.9 x 0.798)
  Skill gate STRICT   : arm exact-match >= 0.769 (= 0.506 + 0.9 x gap)
  Forgetting gate     : intervention cost c-b = arm_ppl - 50.83 <= +1.0 ppl

Reads each arm's OWN measured step-5000 metrics row (anchors re-read the
same way for internal consistency; compared against the pre-registered
constants above). Reports aggregate + per-(digit x carry) exact-match.

Runs on whatever arms have reached step 5000; pending arms are listed.
Usage: python scripts/week4_arith_report.py
"""
from __future__ import annotations

import sys
from pathlib import Path

import pandas as pd

PROJECT_ROOT = Path(r"D:\EXPERIMENTS\reopen")
sys.path.insert(0, str(PROJECT_ROOT))

from reopen.checkpoint import load_checkpoint  # noqa: E402
from reopen.config import CHECKPOINT_DIR, DATA_DIR, LOG_DIR, ModelConfig  # noqa: E402
from reopen.model import GPT  # noqa: E402

from arith_breakdown import grade_detailed, load_eval_problems  # noqa: E402

SRC = "arith_delay50_exp20_size23M_seed1"
FINAL = 5000

# pre-registered anchors + gates (constants, not fit to results)
BASE_ACC, BASE_PPL = 0.798, 48.19          # (a) delay-0
NULL_ACC, NULL_PPL = 0.506, 50.83          # (b) d50 null
GAP = BASE_ACC - NULL_ACC                   # 0.292
GATE_PRIMARY = 0.9 * BASE_ACC               # 0.718
GATE_STRICT = NULL_ACC + 0.9 * GAP          # 0.769
PPL_COST_GATE = 1.0

# arm label -> run_id suffix (as generated by run_intervention.py)
ARMS = [
    ("null (source)",     ""),                          # the source run itself
    ("reset (emb)",       "_ivresetembedding2501"),
    ("reset+spike",       "_ivresetspikeembedding2501"),
    ("spike",             "_ivspike2501"),
    ("freeze (emb)",      "_ivfreeze2501"),
    ("cram",              "_ivcram2501"),
    ("lr_shift (seg 0)",  "_ivlrshift0at2501"),
]


def final_row(run_id: str):
    m = LOG_DIR / run_id / "metrics.csv"
    if not m.exists():
        return None
    df = pd.read_csv(m)
    hit = df[df.step == FINAL]
    return hit.iloc[-1] if len(hit) else None


def main() -> None:
    from tokenizers import Tokenizer
    tok = Tokenizer.from_file(str(DATA_DIR / "tokenized" / "tokenizer.json"))
    problems = load_eval_problems()

    lines: list[str] = []

    def out(s: str = "") -> None:
        print(s)
        lines.append(s)

    out("# Week 4 arith reopening pilot — read-out")
    out("")
    out(f"Common checkpoint: {SRC} @ step 2500 "
        "(sha 1fa5e0a2...). All arms fork from it.")
    out(f"Anchors (pre-registered): delay-0 {BASE_ACC:.3f}@{BASE_PPL} ppl | "
        f"d50 null {NULL_ACC:.3f}@{NULL_PPL} ppl | gap {GAP:.3f}")
    out(f"Skill gate: PRIMARY >= {GATE_PRIMARY:.3f}, STRICT >= "
        f"{GATE_STRICT:.3f}. Forgetting gate: c-b <= +{PPL_COST_GATE} ppl.")
    out("")
    out("| arm | exact | recovery% | val_ppl | iv cost c-b | skill | forget |")
    out("|-----|-------|-----------|---------|-------------|-------|--------|")

    model = None
    per_band = {}
    pending = []
    for label, suffix in ARMS:
        run_id = SRC + suffix
        row = final_row(run_id)
        if row is None:
            pending.append(label)
            out(f"| {label} | _pending_ | | | | | |")
            continue
        acc = float(row["arith_accuracy"])
        ppl = float(row["val_ppl"])
        rec = (acc - NULL_ACC) / GAP * 100
        cost = ppl - NULL_PPL
        skill = ("STRICT" if acc >= GATE_STRICT else
                 "PRIMARY" if acc >= GATE_PRIMARY else "no")
        forget = "OK" if cost <= PPL_COST_GATE else "FLAG"
        out(f"| {label} | {acc:.3f} | {rec:+.0f}% | {ppl:.2f} | "
            f"{cost:+.2f} | {skill} | {forget} |")

        # per-band exact-match at the final checkpoint
        cdir = CHECKPOINT_DIR / run_id
        fp = cdir / f"step_{FINAL:07d}.pt"
        if fp.exists():
            ck = load_checkpoint(fp, device="cpu")
            if model is None:
                model = GPT(ModelConfig(**ck["model_config"])).to("cuda")
            model.load_state_dict(ck["model"])
            df = grade_detailed(model, tok, problems, "cuda")
            band = df.groupby(["digits", "carry"]).exact.mean()
            per_band[label] = band

    out("")
    if pending:
        out(f"**Pending arms (not yet at step {FINAL}):** "
            + ", ".join(pending))
        out("")

    if per_band:
        out("## Per-band exact-match (digits x carry) at step 5000")
        out("")
        bands = pd.DataFrame(per_band)
        out("```")
        out(bands.to_string(float_format=lambda v: f"{v:.3f}"))
        out("```")

    out_dir = LOG_DIR / "week4_arith_pilot"
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "report.md").write_text("\n".join(lines), encoding="utf-8")
    print(f"\nwrote {out_dir / 'report.md'}")


if __name__ == "__main__":
    main()
