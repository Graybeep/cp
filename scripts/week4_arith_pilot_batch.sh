#!/usr/bin/env bash
# Week 4 arithmetic reopening pilot — launch the 6 intervention arms.
#
# All arms fork from the SINGLE common checkpoint (locked, CLAUDE.md Week 4):
#   arith_delay50_exp20_size23M_seed1 @ step 2500
#   sha256 1fa5e0a28bd798e0a9b0d2f5753c000749b45fab1c717f42b221e6a5d28d7ba9
# Arm 0 (null) = the source run itself, already trained to step 5000 (free).
#
# Each arm runs steps 2501->5000 (~15 min). run_intervention.py is
# kill-tolerant: re-running resumes the fork's own latest checkpoint. This
# batch additionally SKIPS any arm already at step_0005000.pt so a
# harness-kill relaunch does not redo finished arms (avoids full stream
# replay).
#
# Params are the pre-registered pilot defaults (notes/week4-arith-pilot-design.md):
#   spike peak 6e-4 / 300 steps, freeze/cram windows 500 steps.
set -u
cd "$(dirname "$0")/.." || exit 1

SRC=arith_delay50_exp20_size23M_seed1
FORK_STEP=2500
PY=.venv/Scripts/python.exe
LOGDIR=logs/week4_arith_pilot
mkdir -p "$LOGDIR"

# arm_name  suffix(as generated by run_intervention)  extra-args
run_arm () {
  local name="$1"; local suffix="$2"; shift 2
  local run_id="${SRC}_${suffix}"
  local done_ckpt="checkpoints/${run_id}/step_0005000.pt"
  echo "=== [$(date +%H:%M:%S)] ARM ${name} -> ${run_id} ==="
  if [ -f "$done_ckpt" ]; then
    echo "    already complete (step_0005000.pt present) — skipping"
    return 0
  fi
  "$PY" scripts/run_intervention.py \
      --from-run "$SRC" --fork-step "$FORK_STEP" \
      "$@" > "${LOGDIR}/${name}.out" 2> "${LOGDIR}/${name}.err"
  local code=$?
  echo "    exit ${code} (log: ${LOGDIR}/${name}.out)"
  return $code
}

echo "###### Week 4 arith pilot batch start $(date) ######"

run_arm reset        ivresetembedding2501       --intervention reset
run_arm reset_spike  ivresetspikeembedding2501  --intervention reset_spike
run_arm spike        ivspike2501                --intervention spike
run_arm freeze       ivfreeze2501               --intervention freeze
run_arm cram         ivcram2501                 --intervention cram
run_arm lr_shift     ivlrshift0at2501           --intervention lr_shift --shift-source-start 0

echo "###### Week 4 arith pilot batch done $(date) ######"
