#!/usr/bin/env bash
# Bring the five single-seed intervention arms to n = 3.
#
# WHY: reset / reset_spike / spike / cram / freeze are all n = 1 in the Week 4
# pilot. Four of them carry "no detectable recovery" and FREEZE carries a
# DIRECTIONAL claim ("harmful", endpoint 0.332, below the entire null range) —
# on one run. The paper labels them SUGGESTIVE (n=1) and says "one seed cannot
# support 'fails to reopen'", but a reviewer will ask for the seeds regardless:
# the caveat protects the claim from being wrong, not from being asked to fix.
#
# lr_shift and cram_lrshift are already n = 3 and are NOT re-run here.
#
# Every arm forks from the SAME common checkpoint its seed-1 counterpart used
# (arith_delay50_exp20_size23M_seed{S} @ step 2500) with the SAME pre-registered
# pilot defaults (spike peak 6e-4 / 300 steps, freeze+cram windows 500 steps) —
# no flags beyond --intervention, exactly as scripts/week4_arith_pilot_batch.sh
# ran them. Comparability across seeds requires identical hyperparameters.
#
# Reading rule: notes/intervention-arms-n3-preregistration.md
set -u
cd "$(dirname "$0")/.." || exit 1

PY=.venv/Scripts/python.exe
FORK_STEP=2500
LOGDIR=logs/intervention_arms_n3
mkdir -p "$LOGDIR"

# arm_name  suffix(as generated by run_intervention)  extra-args
run_arm () {
  local seed="$1"; local name="$2"; local suffix="$3"; shift 3
  local src="arith_delay50_exp20_size23M_seed${seed}"
  local run_id="${src}_${suffix}"
  local done_ckpt="checkpoints/${run_id}/step_0005000.pt"
  echo "=== [$(date +%F' '%H:%M:%S)] seed${seed} ARM ${name} -> ${run_id} ==="
  if [ -f "$done_ckpt" ]; then
    echo "    already complete (step_0005000.pt present) — skipping"
    return 0
  fi
  if [ ! -f "checkpoints/${src}/step_000${FORK_STEP}.pt" ]; then
    echo "    MISSING FORK SOURCE checkpoints/${src}/step_000${FORK_STEP}.pt"
    return 1
  fi
  "$PY" scripts/run_intervention.py \
      --from-run "$src" --fork-step "$FORK_STEP" \
      "$@" > "${LOGDIR}/seed${seed}_${name}.out" \
           2> "${LOGDIR}/seed${seed}_${name}.err"
  local code=$?
  echo "    exit ${code} (log: ${LOGDIR}/seed${seed}_${name}.out)"
  return $code
}

echo "###### intervention arms -> n=3 start $(date) ######"

for seed in 2 3; do
  run_arm "$seed" reset       ivresetembedding2501      --intervention reset       || echo "ARM-FAILURE seed$seed reset"
  run_arm "$seed" reset_spike ivresetspikeembedding2501 --intervention reset_spike || echo "ARM-FAILURE seed$seed reset_spike"
  run_arm "$seed" spike       ivspike2501               --intervention spike       || echo "ARM-FAILURE seed$seed spike"
  run_arm "$seed" freeze      ivfreeze2501              --intervention freeze      || echo "ARM-FAILURE seed$seed freeze"
  run_arm "$seed" cram        ivcram2501                --intervention cram        || echo "ARM-FAILURE seed$seed cram"
done

echo "###### intervention arms -> n=3 done $(date) ######"
echo "ARMS-N3-COMPLETE $(date '+%F %T')"
